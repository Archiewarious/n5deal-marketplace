/**
 * Three languages, one dictionary, no library.
 *
 * The assignment lists multi-language support as a plus and the hiring conversation runs in
 * Ukrainian, so English, Ukrainian and Russian. The machinery is forty lines because that is all
 * this needs: a flat record per locale, a lookup that falls back to English rather than to a raw
 * key, and `{name}` interpolation. next-intl and react-i18next both solve routing, pluralisation
 * rules and lazy namespace loading, none of which is a problem here.
 *
 * The locale lives in a cookie rather than in the path, and that is a deliberate trade.
 * `/uk/assets` is the right answer for a public catalogue, because a URL that names its language
 * is shareable and indexable. But eleven of this app's twelve routes sit behind auth and the
 * whole site is `robots: noindex` — there is no index to be in — so a path segment would buy
 * nothing and cost a rewrite of every internal href. If the catalogue were ever made public,
 * that trade flips, and the dictionary below would not have to change for it.
 *
 * What is NOT translated: the listings themselves. A licence written up in English by its seller
 * stays in English, because machine-translating the description of a regulated entity into a
 * language the seller cannot check is worse than leaving it alone. That is a content problem,
 * not a UI one.
 */

export const LOCALES = ['en', 'uk', 'ru'] as const
export type Locale = (typeof LOCALES)[number]

export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  uk: 'Українська',
  ru: 'Русский',
}

/** Short label for the switcher, where there is room for two characters. */
export const LOCALE_SHORT: Record<Locale, string> = { en: 'EN', uk: 'UA', ru: 'RU' }

export const LOCALE_COOKIE = 'locale'

export function isLocale(v: unknown): v is Locale {
  return typeof v === 'string' && (LOCALES as readonly string[]).includes(v)
}

