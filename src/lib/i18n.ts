const DICT: Record<Locale, Dict> = { en, uk, ru }

/**
 * Falls back to English rather than to the key, because a missing Ukrainian string should read
 * as English text and not as `assets.emptyTitle`. The English dictionary is the contract: a key
 * missing from it is a bug, and `t` says so loudly enough to be noticed in development.
 */
export function translator(locale: Locale) {
  return function t(key: string, vars?: Record<string, string | number>): string {
    let s = DICT[locale][key] ?? en[key]
    if (s === undefined) {
      if (process.env.NODE_ENV !== 'production') console.warn(`i18n: no string for "${key}"`)
      return key
    }
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

export type T = ReturnType<typeof translator>

