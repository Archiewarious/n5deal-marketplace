#!/usr/bin/env node
// Хук: перед правкою ІНТЕРФЕЙСУ нагадати, що є методика дизайну — і чи вона відкрита.
//
// ⚠️ НАВІЩО (23.08.2026, питання власника «як зробити, щоб ти цим завжди
// користувався?»). Того дня в системі лежали frontend-design, motion-design,
// motion-dev-animations, ui-ux-pro-max, design-system і ще півдесятка скілів —
// а весь редизайн «Журналу подій» був зроблений на здоровому глузді. Скіл
// frontend-design відкривався двічі, решта — жодного разу. Наслідок: чотири
// кола переробок і оцінка власника «виглядає дешево».
//
// Причина не в лінощах, а в механіці: правило, яке агент має ЗГАДАТИ, відмовляє
// саме тоді, коли він захоплений задачею. Той самий висновок уже записаний у
// settings.json цього проєкту: «правило в CLAUDE.md вмирає через 20 викликів
// інструментів, хук не вмирає».
//
// ЩО РОБИТЬ: перед Edit/Write у файл інтерфейсу перевіряє, чи відкривався в цій
// сесії скіл дизайну. Якщо ні — друкує нагадування в stderr. НЕ блокує: правка
// підпису кнопки або одного рядка тексту методики не потребує, і блокування
// перетворило б бар'єр на перешкоду.
//
// ЯК ЗНАЄ, ЩО СКІЛ ВІДКРИВАЛИ: парний хук mark-design-skill.js ставить мітку у
// файл сесії при виклику Skill. Мітка живе в теці сесії, тож нова розмова
// починається з чистого аркуша — і нагадування приходить знову.
//
// Запуск і без хука: node .claude/hooks/require-design-skill.js <файл>

const fs = require('fs')
const os = require('os')
const path = require('path')

// Файли, які МАЛЮЮТЬ інтерфейс. Логіка (lib/**) і тести сюди не входять: там
// методика дизайну ні до чого.
const UI = [/src[\\/]components[\\/].*\.tsx$/i, /src[\\/]app[\\/].*\.tsx$/i, /globals\.css$/i]

const SKILLS = [
  'frontend-design — типографіка, палітра, план ДО коду, анти-шаблонність',
  'motion-design / motion-dev-animations — анімація з reduced-motion і 60fps',
  'ui-ux-pro-max, design-system, ui-styling — компоненти й токени',
  'design:design-critique — критика власної роботи ПЕРЕД показом власнику',
  'design:ux-copy — тексти в інтерфейсі; design:accessibility-review — доступність',
]

function markerPath() {
  // Мітка сесії: id сесії дає CLAUDE_SESSION_ID, а без нього — теку проєкту.
  const id = process.env.CLAUDE_SESSION_ID || process.env.CLAUDE_PROJECT_DIR || 'default'
  const safe = String(id).replace(/[^a-z0-9]+/gi, '-').slice(-60)
  return path.join(os.tmpdir(), `claude-design-skill-${safe}.flag`)
}

function main() {
  const file = process.argv[2] || process.env.CLAUDE_TOOL_FILE_PATH || ''
  if (!file || !UI.some((re) => re.test(file))) return

  // Скіл уже відкривали в цій сесії — мовчимо.
  try {
    if (fs.existsSync(markerPath())) return
  } catch {
    return
  }

  process.stderr.write(
    [
      '',
      '🎨 ПРАВКА ІНТЕРФЕЙСУ — а методику дизайну в цій сесії ще не відкривали.',
      '',
      '   Skill(frontend-design) — і далі за потребою:',
      ...SKILLS.map((s) => `   • ${s}`),
      '',
      '   ⚠️ 23.08.2026 весь редизайн зробили без них — чотири кола переробок',
      '   і «виглядає дешево» від власника. Скіли лежали на місці й не відкривались.',
      '',
      '   Не потрібно для: підпису кнопки, тексту, одного рядка. Потрібно для:',
      '   нового екрана, перекомпонування, «зроби красиво», будь-якої правки подачі.',
      '',
    ].join('\n'),
  )
}

try {
  main()
} catch {
  // Хук не має права валити роботу: будь-яка помилка — тиша.
}
process.exit(0)
